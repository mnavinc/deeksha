// ─── HELPER: get journey array for a deeksha type ───────────────────────────
export function getJourneyForDeeksha(deekshaId: string): JourneyCheckpoint[] {
  switch (deekshaId) {
    case 'bhavani': return BHAVANI_JOURNEY;
    case 'govinda': return GOVINDA_JOURNEY;
    case 'shiva':   return SHIVA_JOURNEY;
    case 'hanuman': return HANUMAN_JOURNEY;
    case 'ayyappa':
    default:        return AYYAPPA_JOURNEY;
  }
}

